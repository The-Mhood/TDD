#!/usr/bin/env python3
"""Apply the mechanical build-compatibility fixes that build_readiness.py reports.

DRY RUN BY DEFAULT. Nothing is written unless you pass --apply.

  python3 Tools/engine/fix_readiness.py <tree>            # show the plan
  python3 Tools/engine/fix_readiness.py <tree> --apply    # write it

Only fixes whose correct form is forced by the compiler/linker are applied:

  1. a module declared in the descriptor with no IMPLEMENT_MODULE translation unit
     -> create Source/<Module>/Private/<Module>Module.cpp (the link fails without it)
  2. EngineIncludeOrderVersion pinned to a different engine minor than the project
     -> EngineIncludeOrderVersion.Latest
  3. a module typed Runtime that depends on an editor-only module
     -> "Type": "Editor"  (a Runtime module cannot link UnrealEd; this is forced,
        not a choice, and it is not a decision about module architecture)
  4. a target whose ExtraModuleNames does not reach a module of its own type
     -> append ExtraModuleNames.Add("<Module>") after the existing line

It does not touch gameplay code, does not rename or reorganise modules, and does
not build. Re-run build_readiness.py afterwards.
"""

import argparse
import json
import pathlib
import re

EDITOR_ONLY = ("UnrealEd", "EditorStyle", "ToolMenus", "DetailCustomizations", "EditorFramework",
               "PropertyEditor", "AssetTools", "DataValidation", "EditorScriptingUtilities",
               "PlacementMode", "ClassViewer", "GraphEditor")


def find_descriptor(root):
    found = sorted(root.glob("*.uproject"))
    return found[0] if found else None


def module_object_span(text, name):
    """Character span of the brace-balanced object containing "Name": "<name>"."""
    m = re.search(r'"Name"\s*:\s*"%s"' % re.escape(name), text)
    if not m:
        return None
    start = text.rfind("{", 0, m.start())
    if start < 0:
        return None
    depth = 0
    for i in range(start, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return start, i + 1
    return None


def build_cs_deps(path):
    text = path.read_text(encoding="utf-8", errors="ignore")
    names = (re.findall(r"PublicDependencyModuleNames\s*\.\s*Add(?:Range)?\s*\(([^;]*)\)", text, re.S)
             + re.findall(r"PrivateDependencyModuleNames\s*\.\s*Add(?:Range)?\s*\(([^;]*)\)", text, re.S))
    return {n for chunk in names for n in re.findall(r'"([A-Za-z0-9_]+)"', chunk)}


def plan(root):
    desc = find_descriptor(root)
    if not desc:
        raise SystemExit(f"no .uproject in {root}")
    proj = json.loads(desc.read_text(encoding="utf-8"))
    modules = proj.get("Modules", [])
    src = root / "Source"
    assoc = str(proj.get("EngineAssociation", ""))
    actions = []   # (kind, path, description, callable)

    # ---- 1 and 3: module-level fixes
    deps, mtype = {}, {}
    for m in modules:
        name = m.get("Name")
        mtype[name] = m.get("Type")
        bcs = src / name / f"{name}.Build.cs"
        deps[name] = build_cs_deps(bcs) if bcs.is_file() else set()

        if not (src / name).is_dir():
            continue
        tusp = [p for p in (src / name).rglob("*.cpp")
                if re.search(r"IMPLEMENT_(PRIMARY_GAME_MODULE|MODULE)\s*\(", p.read_text(encoding="utf-8", errors="ignore"))]
        if not tusp:
            target = src / name / "Private" / f"{name}Module.cpp"
            body = (
                "// Copyright (c) 2026. The Disobedient Daughter.\n"
                f"// Generated by Tools/engine/fix_readiness.py: {name} is declared in the descriptor\n"
                "// but had no module implementation, which fails at link time.\n\n"
                '#include "Modules/ModuleManager.h"\n\n'
                f"IMPLEMENT_MODULE(FDefaultModuleImpl, {name})\n"
            )
            actions.append(("create", target, f"{name}: module implementation unit", body))

    # collect every Runtime module that links editor-only modules, then rewrite the
    # descriptor once so several retypes cannot clobber each other
    retype = []
    for m in modules:
        name = m.get("Name")
        if mtype.get(name) != "Runtime":
            continue
        editor_deps = sorted(d for d in deps.get(name, ()) if d in EDITOR_ONLY)
        if editor_deps:
            retype.append((name, editor_deps))

    if retype:
        text = desc.read_text(encoding="utf-8")
        reasons = []
        for name, editor_deps in retype:
            span = module_object_span(text, name)
            if not span:
                continue
            block = text[span[0]:span[1]]
            new_block = re.sub(r'("Type"\s*:\s*)"Runtime"', r'\1"Editor"', block, count=1)
            if new_block == block:
                continue
            text = text[:span[0]] + new_block + text[span[1]:]
            mtype[name] = "Editor"
            reasons.append(f'{name} -> Editor (depends on editor-only {", ".join(editor_deps)})')
        if reasons:
            def write_desc(p=desc, payload=text):
                p.write_text(payload, encoding="utf-8")

            actions.append(("edit", desc,
                            '"Type": "Runtime" -> "Editor" for ' + "; ".join(reasons)
                            + " (a Runtime module cannot link editor-only modules)",
                            write_desc))

    # ---- 2: include order
    for cs in sorted(src.glob("*.Target.cs")):
        text = cs.read_text(encoding="utf-8")
        pin = re.search(r"EngineIncludeOrderVersion\s*\.\s*Unreal5_(\d+)", text)
        if not pin or not assoc.startswith("5."):
            continue
        if int(pin.group(1)) == int(assoc.split(".")[1]):
            continue
        new_text = re.sub(r"EngineIncludeOrderVersion\s*\.\s*Unreal5_\d+",
                          "EngineIncludeOrderVersion.Latest", text)

        def write_cs(p=cs, payload=new_text):
            p.write_text(payload, encoding="utf-8")

        actions.append(("edit", cs,
                        f"{cs.name}: include order 5.{pin.group(1)} -> Latest (project targets {assoc})",
                        write_cs))

    # ---- 4: ExtraModuleNames coverage, after the type fixes above
    runtime_like = [n for n in mtype if mtype[n] == "Runtime"]
    editor_like = [n for n in mtype if mtype[n] == "Editor"]
    for cs in sorted(src.glob("*.Target.cs")):
        text = cs.read_text(encoding="utf-8")
        listed = []
        for call in re.finditer(r"ExtraModuleNames\s*\.\s*Add(?:Range)?\s*\(([^;]*)\)\s*;", text, re.S):
            listed += re.findall(r'"([A-Za-z0-9_]+)"', call.group(1))
        if not listed:
            continue
        wanted = [n for n in (editor_like if "Editor" in cs.name else runtime_like)
                  if (src / n / f"{n}.Build.cs").is_file()]
        reachable, frontier = set(listed), list(listed)
        while frontier:
            cur = frontier.pop()
            for d in deps.get(cur, ()):
                if d not in reachable:
                    reachable.add(d)
                    frontier.append(d)
        missing = [n for n in wanted if n not in reachable]
        if not missing:
            continue
        line = re.search(r"^([ \t]*)ExtraModuleNames\s*\.\s*Add(?:Range)?\s*\([^;]*\)\s*;", text, re.M)
        if not line:
            continue
        indent = line.group(1)
        addition = "".join(f'\n{indent}ExtraModuleNames.Add("{n}");' for n in missing)
        new_text = text[:line.end()] + addition + text[line.end():]

        def write_target(p=cs, payload=new_text, names=missing):
            p.write_text(payload, encoding="utf-8")

        actions.append(("edit", cs,
                        f'{cs.name}: ExtraModuleNames += {missing} (not reachable from the listed modules)',
                        write_target))

    return desc, actions


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("root", nargs="?", default=".")
    ap.add_argument("--apply", action="store_true", help="write the changes (default: dry run)")
    args = ap.parse_args()
    root = pathlib.Path(args.root).resolve()

    desc, actions = plan(root)
    print(f"project: {desc.relative_to(root)}")
    if not actions:
        print("nothing to fix: the forced compatibility fixes are already in place.")
        return 0

    for kind, path, what, _ in actions:
        print(f"  {'CREATE' if kind == 'create' else 'EDIT  '} {path.relative_to(root)}")
        print(f"         {what}")

    if not args.apply:
        print(f"\n{len(actions)} change(s) planned. Nothing was written. Re-run with --apply.")
        return 0

    for kind, path, what, apply_change in actions:
        if kind == "create":
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(apply_change, encoding="utf-8")
        else:
            apply_change()
        print(f"applied: {path.relative_to(root)}")
    print("\nwritten. Re-run Tools/engine/build_readiness.py to confirm, then build.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
